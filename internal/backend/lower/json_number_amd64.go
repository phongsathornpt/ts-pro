package lower

import (
	"encoding/binary"

	"github.com/phongsathornpt/ts-pro/internal/backend/asm/amd64"
)

// emitAMD64JSONNumberValid validates the complete JSON number grammar.
// RDI = native string, RAX = 0/1.
func emitAMD64JSONNumberValid(e *amd64.Emitter) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }

	e.MovRegDeref(amd64.R9, amd64.RDI, 0)
	e.MovRegReg(amd64.R8, amd64.RDI)
	e.AddRegImm32(amd64.R8, 8)
	e.TestRegReg(amd64.R9, amd64.R9)
	empty := len(e.Code)
	e.JccRel32(amd64.CondE, 0)

	// Optional minus.
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	e.CmpRegImm32(amd64.R10, '-')
	noMinus := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	e.TestRegReg(amd64.R9, amd64.R9)
	minusOnly := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	patchJcc(noMinus, len(e.Code))

	// Integer part: 0 or [1-9][0-9]*.
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	e.CmpRegImm32(amd64.R10, '0')
	zeroInt := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.CmpRegImm32(amd64.R10, '1')
	badIntLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, '9')
	badIntHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)

	intLoop := len(e.Code)
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	e.TestRegReg(amd64.R9, amd64.R9)
	intEOF := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	e.CmpRegImm32(amd64.R10, '0')
	intDoneLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, '9')
	intDoneHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	intBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(intBack, intLoop)

	zeroLabel := len(e.Code)
	patchJcc(zeroInt, zeroLabel)
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	e.TestRegReg(amd64.R9, amd64.R9)
	zeroEOF := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	// A digit immediately after a leading zero is invalid.
	e.CmpRegImm32(amd64.R10, '0')
	zeroNotDigitLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, '9')
	zeroNotDigitHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	leadingZeroInvalid := len(e.Code)
	e.JmpRel32(0)

	afterInt := len(e.Code)
	patchJcc(intDoneLow, afterInt)
	patchJcc(intDoneHigh, afterInt)
	patchJcc(zeroNotDigitLow, afterInt)
	patchJcc(zeroNotDigitHigh, afterInt)
	// Optional fraction.
	e.CmpRegImm32(amd64.R10, '.')
	noFraction := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	e.TestRegReg(amd64.R9, amd64.R9)
	fractionMissing := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	e.CmpRegImm32(amd64.R10, '0')
	fractionBadLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, '9')
	fractionBadHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)

	fracLoop := len(e.Code)
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	e.TestRegReg(amd64.R9, amd64.R9)
	fracEOF := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	e.CmpRegImm32(amd64.R10, '0')
	fracDoneLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, '9')
	fracDoneHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	fracBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(fracBack, fracLoop)

	afterFrac := len(e.Code)
	patchJcc(noFraction, afterFrac)
	patchJcc(fracDoneLow, afterFrac)
	patchJcc(fracDoneHigh, afterFrac)
	// Optional exponent.
	e.CmpRegImm32(amd64.R10, 'e')
	isLowerE := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.CmpRegImm32(amd64.R10, 'E')
	noExponent := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	patchJcc(isLowerE, len(e.Code))
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	e.TestRegReg(amd64.R9, amd64.R9)
	exponentMissing := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	e.CmpRegImm32(amd64.R10, '+')
	expPlus := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.CmpRegImm32(amd64.R10, '-')
	expNoSign := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	patchJcc(expPlus, len(e.Code))
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	e.TestRegReg(amd64.R9, amd64.R9)
	exponentSignOnly := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	patchJcc(expNoSign, len(e.Code))
	e.CmpRegImm32(amd64.R10, '0')
	exponentBadLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, '9')
	exponentBadHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)

	expLoop := len(e.Code)
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	e.TestRegReg(amd64.R9, amd64.R9)
	expEOF := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	e.CmpRegImm32(amd64.R10, '0')
	expDoneLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, '9')
	expDoneHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	expBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(expBack, expLoop)

	// Non-EOF after a number is invalid because the validator receives the
	// complete token, not the surrounding JSON source.
	invalid := len(e.Code)
	for _, at := range []int{empty, minusOnly, badIntLow, badIntHigh, fractionMissing, fractionBadLow, fractionBadHigh, exponentMissing, exponentSignOnly, exponentBadLow, exponentBadHigh} {
		patchJcc(at, invalid)
	}
	patchJmp(leadingZeroInvalid, invalid)
	patchJcc(noExponent, invalid)
	patchJcc(expDoneLow, invalid)
	patchJcc(expDoneHigh, invalid)
	e.MovRegImm64(amd64.RAX, 0)
	invalidDone := len(e.Code)
	e.JmpRel32(0)

	valid := len(e.Code)
	for _, at := range []int{intEOF, zeroEOF, fracEOF, expEOF} {
		patchJcc(at, valid)
	}
	e.MovRegImm64(amd64.RAX, 1)
	done := len(e.Code)
	patchJmp(invalidDone, done)
	e.Ret()
}
