func emitAMD64HexNibble(e *amd64.Emitter) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }
	e.MovRegReg(amd64.RAX, amd64.RDI)
	e.CmpRegImm32(amd64.RAX, '0')
	notDigitLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.RAX, '9')
	notDigitHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	e.SubRegImm32(amd64.RAX, '0')
	digitDone := len(e.Code)
	e.JmpRel32(0)

	upper := len(e.Code)
	patchJcc(notDigitLow, upper)
	patchJcc(notDigitHigh, upper)
	e.MovRegReg(amd64.RAX, amd64.RDI)
	e.CmpRegImm32(amd64.RAX, 'A')
	notUpperLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.RAX, 'F')
	notUpperHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	e.SubRegImm32(amd64.RAX, 'A'-10)
	upperDone := len(e.Code)
	e.JmpRel32(0)

	lower := len(e.Code)
	patchJcc(notUpperLow, lower)
	patchJcc(notUpperHigh, lower)
	e.MovRegReg(amd64.RAX, amd64.RDI)
	e.CmpRegImm32(amd64.RAX, 'a')
	notLowerLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.RAX, 'f')
	notLowerHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	e.SubRegImm32(amd64.RAX, 'a'-10)
	lowerDone := len(e.Code)
	e.JmpRel32(0)

	invalid := len(e.Code)
	patchJcc(notLowerLow, invalid)
	patchJcc(notLowerHigh, invalid)
	e.MovRegImm64(amd64.RAX, -1)
	done := len(e.Code)
	for _, at := range []int{digitDone, upperDone, lowerDone} {
		patchJmp(at, done)
	}
	e.Ret()
}

func emitAMD64FormURLDecodeBytes(e *amd64.Emitter, byteBufferNewOffset, hexOffset int) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }
	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	e.SubRegImm32(amd64.RSP, 32)
	e.MovRegReg(amd64.RBX, amd64.RDI)
	e.MovRegDeref(amd64.R12, amd64.RBX, 0)

	// Root source across ByteBuffer allocation.
	e.MovRegDeref(amd64.R10, amd64.R15, amd64RTRootHead)
	e.MovDerefReg(amd64.RSP, 0, amd64.R10)
	e.MovRegImm64(amd64.R10, 1)
	e.MovDerefReg(amd64.RSP, 8, amd64.R10)
	e.MovDerefReg(amd64.RSP, 16, amd64.RBX)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.RSP)
	e.Cvtsi2sd(amd64.XMM0, amd64.R12)
	callNew := len(e.Code)
	e.CallRel32(int32(byteBufferNewOffset - (callNew + 5)))
	e.MovRegReg(amd64.R14, amd64.RAX)
	e.MovRegDeref(amd64.R10, amd64.RSP, 0)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.R10)
	e.MovRegImm64(amd64.R13, 0)             // source index
	e.MovDerefReg(amd64.RSP, 24, amd64.R13) // written count

	loop := len(e.Code)
	e.CmpRegReg(amd64.R13, amd64.R12)
	doneJump := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.R10, amd64.RBX)
	e.AddRegImm32(amd64.R10, 8)
	e.AddRegReg(amd64.R10, amd64.R13)
	e.MovzxRegDeref8(amd64.RAX, amd64.R10, 0)

	e.CmpRegImm32(amd64.RAX, '+')
	plusJump := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.CmpRegImm32(amd64.RAX, '%')
	percentJump := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovRegReg(amd64.RDX, amd64.RAX)
	e.MovRegImm64(amd64.R11, 1)
	rawDone := len(e.Code)
	e.JmpRel32(0)

	plusLabel := len(e.Code)
	patchJcc(plusJump, plusLabel)
	e.MovRegImm64(amd64.RDX, ' ')
	e.MovRegImm64(amd64.R11, 1)
	plusDone := len(e.Code)
	e.JmpRel32(0)

	percentLabel := len(e.Code)
	patchJcc(percentJump, percentLabel)
	e.MovRegReg(amd64.R10, amd64.R13)
	e.AddRegImm32(amd64.R10, 2)
	e.CmpRegReg(amd64.R10, amd64.R12)
	percentInvalidRange := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)

	e.MovRegReg(amd64.R10, amd64.RBX)
	e.AddRegImm32(amd64.R10, 8)
	e.AddRegReg(amd64.R10, amd64.R13)
	e.MovzxRegDeref8(amd64.RDI, amd64.R10, 1)
	callHex1 := len(e.Code)
	e.CallRel32(int32(hexOffset - (callHex1 + 5)))
	e.CmpRegImm32(amd64.RAX, -1)
	percentInvalidFirst := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.Push(amd64.RAX)
	e.MovRegReg(amd64.R10, amd64.RBX)
	e.AddRegImm32(amd64.R10, 8)
	e.AddRegReg(amd64.R10, amd64.R13)
	e.MovzxRegDeref8(amd64.RDI, amd64.R10, 2)
	callHex2 := len(e.Code)
	e.CallRel32(int32(hexOffset - (callHex2 + 5)))
	e.Pop(amd64.R10)
	e.CmpRegImm32(amd64.RAX, -1)
	percentInvalidSecond := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.AddRegReg(amd64.R10, amd64.R10)
	e.AddRegReg(amd64.R10, amd64.R10)
	e.AddRegReg(amd64.R10, amd64.R10)
	e.AddRegReg(amd64.R10, amd64.R10)
	e.OrRegReg(amd64.R10, amd64.RAX)
	e.MovRegReg(amd64.RDX, amd64.R10)
	e.MovRegImm64(amd64.R11, 3)
	percentDone := len(e.Code)
	e.JmpRel32(0)

	percentInvalid := len(e.Code)
	patchJcc(percentInvalidRange, percentInvalid)
	patchJcc(percentInvalidFirst, percentInvalid)
	patchJcc(percentInvalidSecond, percentInvalid)
	e.MovRegImm64(amd64.RDX, '%')
	e.MovRegImm64(amd64.R11, 1)

	writeLabel := len(e.Code)
	for _, at := range []int{rawDone, plusDone, percentDone} {
		patchJmp(at, writeLabel)
	}
	e.MovRegDeref(amd64.R10, amd64.R14, amd64ByteBufferData)
	e.MovRegDeref(amd64.RAX, amd64.RSP, 24)
	e.AddRegReg(amd64.R10, amd64.RAX)
	e.MovDerefReg8(amd64.R10, 0, amd64.RDX)
	e.AddRegImm32(amd64.RAX, 1)
	e.MovDerefReg(amd64.RSP, 24, amd64.RAX)
	e.AddRegReg(amd64.R13, amd64.R11)
	back := len(e.Code)
	e.JmpRel32(0)
	patchJmp(back, loop)

	done := len(e.Code)
	patchJcc(doneJump, done)
	e.MovRegDeref(amd64.RAX, amd64.RSP, 24)
	e.MovDerefReg(amd64.R14, amd64ByteBufferLength, amd64.RAX)
	e.MovRegReg(amd64.RAX, amd64.R14)
	e.AddRegImm32(amd64.RSP, 32)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}

func emitAMD64HexASCII(e *amd64.Emitter) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }
	e.MovRegReg(amd64.RAX, amd64.RDI)
	e.CmpRegImm32(amd64.RAX, 10)
	digit := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.AddRegImm32(amd64.RAX, 'A'-10)
	doneJump := len(e.Code)
	e.JmpRel32(0)
	digitLabel := len(e.Code)
	patchJcc(digit, digitLabel)
	e.AddRegImm32(amd64.RAX, '0')
	patchJmp(doneJump, len(e.Code))
	e.Ret()
}

func emitAMD64FormURLEncode(e *amd64.Emitter, allocOffset, hexASCIIOffset int) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }
	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	e.SubRegImm32(amd64.RSP, 32)

	e.MovRegReg(amd64.RBX, amd64.RDI)
	e.MovRegDeref(amd64.R12, amd64.RBX, 0)
	// Root source across worst-case output allocation (3 bytes per input byte).
	e.MovRegDeref(amd64.R10, amd64.R15, amd64RTRootHead)
	e.MovDerefReg(amd64.RSP, 0, amd64.R10)
	e.MovRegImm64(amd64.R10, 1)
	e.MovDerefReg(amd64.RSP, 8, amd64.R10)
	e.MovDerefReg(amd64.RSP, 16, amd64.RBX)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.RSP)
	e.MovRegReg(amd64.RDI, amd64.R12)
	e.MovRegReg(amd64.R10, amd64.R12)
	e.AddRegReg(amd64.R10, amd64.R10)
	e.AddRegReg(amd64.RDI, amd64.R10)
	e.AddRegImm32(amd64.RDI, 8)
	callAlloc := len(e.Code)
	e.CallRel32(int32(allocOffset - (callAlloc + 5)))
	e.MovRegReg(amd64.R13, amd64.RAX)
	e.MovRegDeref(amd64.R10, amd64.RSP, 0)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.R10)
	e.MovRegImm64(amd64.R14, 0)
	e.MovRegImm64(amd64.R10, 0)
	e.MovDerefReg(amd64.RSP, 24, amd64.R10)

	loop := len(e.Code)
	e.CmpRegReg(amd64.R14, amd64.R12)
	doneJump := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.R10, amd64.RBX)
	e.AddRegImm32(amd64.R10, 8)
	e.AddRegReg(amd64.R10, amd64.R14)
	e.MovzxRegDeref8(amd64.RAX, amd64.R10, 0)

	e.MovDerefReg(amd64.RSP, 16, amd64.RAX)
	e.CmpRegImm32(amd64.RAX, ' ')
	spaceJump := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	var safeJumps []int
	for _, bounds := range [][2]int32{{'0', '9'}, {'A', 'Z'}, {'a', 'z'}} {
		e.CmpRegImm32(amd64.RAX, bounds[0])
		below := len(e.Code)
		e.JccRel32(amd64.CondB, 0)
		e.CmpRegImm32(amd64.RAX, bounds[1])
		safe := len(e.Code)
		e.JccRel32(amd64.CondBE, 0)
		patchJcc(below, len(e.Code))
		safeJumps = append(safeJumps, safe)
	}
	for _, ch := range []int32{'*', '-', '.', '_'} {
		e.CmpRegImm32(amd64.RAX, ch)
		safe := len(e.Code)
		e.JccRel32(amd64.CondE, 0)
		safeJumps = append(safeJumps, safe)
	}

	// Percent-encode one UTF-8 byte.
	e.MovRegDeref(amd64.R10, amd64.RSP, 24)
	e.MovRegReg(amd64.R11, amd64.R13)
	e.AddRegImm32(amd64.R11, 8)
	e.AddRegReg(amd64.R11, amd64.R10)
	e.MovRegImm64(amd64.RAX, '%')
	e.MovDerefReg8(amd64.R11, 0, amd64.RAX)

	e.MovRegDeref(amd64.RDI, amd64.RSP, 16)
	e.ShrRegImm8(amd64.RDI, 4)
	callHigh := len(e.Code)
	e.CallRel32(int32(hexASCIIOffset - (callHigh + 5)))
	e.MovRegDeref(amd64.R10, amd64.RSP, 24)
	e.MovRegReg(amd64.R11, amd64.R13)
	e.AddRegImm32(amd64.R11, 9)
	e.AddRegReg(amd64.R11, amd64.R10)
	e.MovDerefReg8(amd64.R11, 0, amd64.RAX)
	e.MovRegDeref(amd64.RDI, amd64.RSP, 16)
	e.MovRegImm64(amd64.RAX, 15)
	e.AndRegReg(amd64.RDI, amd64.RAX)
	callLow := len(e.Code)
	e.CallRel32(int32(hexASCIIOffset - (callLow + 5)))
	e.MovRegDeref(amd64.R10, amd64.RSP, 24)
	e.MovRegReg(amd64.R11, amd64.R13)
	e.AddRegImm32(amd64.R11, 10)
	e.AddRegReg(amd64.R11, amd64.R10)
	e.MovDerefReg8(amd64.R11, 0, amd64.RAX)
	e.AddRegImm32(amd64.R10, 3)
	e.MovDerefReg(amd64.RSP, 24, amd64.R10)
	encodedDone := len(e.Code)
	e.JmpRel32(0)

	safeLabel := len(e.Code)
	for _, at := range safeJumps {
		patchJcc(at, safeLabel)
	}
	e.MovRegDeref(amd64.RAX, amd64.RSP, 16)
	e.MovRegDeref(amd64.R10, amd64.RSP, 24)
	e.MovRegReg(amd64.R11, amd64.R13)
	e.AddRegImm32(amd64.R11, 8)
	e.AddRegReg(amd64.R11, amd64.R10)
	e.MovDerefReg8(amd64.R11, 0, amd64.RAX)
	e.AddRegImm32(amd64.R10, 1)
	e.MovDerefReg(amd64.RSP, 24, amd64.R10)
	safeDone := len(e.Code)
	e.JmpRel32(0)

	spaceLabel := len(e.Code)
	patchJcc(spaceJump, spaceLabel)
	e.MovRegDeref(amd64.R10, amd64.RSP, 24)
	e.MovRegReg(amd64.R11, amd64.R13)
	e.AddRegImm32(amd64.R11, 8)
	e.AddRegReg(amd64.R11, amd64.R10)
	e.MovRegImm64(amd64.RAX, '+')
	e.MovDerefReg8(amd64.R11, 0, amd64.RAX)
	e.AddRegImm32(amd64.R10, 1)
	e.MovDerefReg(amd64.RSP, 24, amd64.R10)

	next := len(e.Code)
	patchJmp(encodedDone, next)
	patchJmp(safeDone, next)
	e.AddRegImm32(amd64.R14, 1)
	back := len(e.Code)
	e.JmpRel32(0)
	patchJmp(back, loop)

	done := len(e.Code)
	patchJcc(doneJump, done)
	e.MovRegDeref(amd64.R10, amd64.RSP, 24)
	e.MovDerefReg(amd64.R13, 0, amd64.R10)
	e.MovRegReg(amd64.RAX, amd64.R13)
	e.AddRegImm32(amd64.RSP, 32)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}
