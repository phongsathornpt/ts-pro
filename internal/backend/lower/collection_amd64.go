const (
	amd64CollectionCount     int32 = 0
	amd64CollectionCapacity  int32 = 8
	amd64CollectionEntries   int32 = 16
	amd64CollectionPayload   int32 = 24
	amd64CollectionEntrySize int32 = 16
)

// emitAMD64JSKeyEq implements SameValueZero for the currently boxed key space.
// RDI/RSi = JSValue keys, RAX = 0/1. Strings compare by value, numeric zeroes
// ignore the sign bit, canonical NaN compares equal to itself, refs by identity.
func emitAMD64JSKeyEq(e *amd64.Emitter, stringEqOffset int) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }

	// Identical bits include canonical NaN and all identical tagged values.
	e.CmpRegReg(amd64.RDI, amd64.RSI)
	rawEqual := len(e.Code)
	e.JccRel32(amd64.CondE, 0)

	// SameValueZero treats +0 and -0 as the same numeric key.
	e.MovRegReg(amd64.R10, amd64.RDI)
	e.MovRegImm64(amd64.R11, int64(0x7fffffffffffffff))
	e.AndRegReg(amd64.R10, amd64.R11)
	e.TestRegReg(amd64.R10, amd64.R10)
	lhsNonZero := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.MovRegReg(amd64.R10, amd64.RSI)
	e.AndRegReg(amd64.R10, amd64.R11)
	e.TestRegReg(amd64.R10, amd64.R10)
	bothZero := len(e.Code)
	e.JccRel32(amd64.CondE, 0)

	checkStrings := len(e.Code)
	patchJcc(lhsNonZero, checkStrings)
	// Unequal tagged strings still compare by content.
	e.MovRegReg(amd64.R10, amd64.RDI)
	e.MovRegImm64(amd64.R11, amd64JSTagMask)
	e.AndRegReg(amd64.R10, amd64.R11)
	e.MovRegImm64(amd64.RAX, amd64JSStringTag)
	e.CmpRegReg(amd64.R10, amd64.RAX)
	notString := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.MovRegReg(amd64.R10, amd64.RSI)
	e.MovRegImm64(amd64.R11, amd64JSTagMask)
	e.AndRegReg(amd64.R10, amd64.R11)
	e.MovRegImm64(amd64.RAX, amd64JSStringTag)
	e.CmpRegReg(amd64.R10, amd64.RAX)
	stringMismatch := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.MovRegImm64(amd64.R10, amd64JSPayloadMask)
	e.AndRegReg(amd64.RDI, amd64.R10)
	e.AndRegReg(amd64.RSI, amd64.R10)
	e.SubRegImm32(amd64.RSP, 8)
	call := len(e.Code)
	e.CallRel32(int32(stringEqOffset - (call + 5)))
	e.AddRegImm32(amd64.RSP, 8)
	e.Ret()

	unequal := len(e.Code)
	patchJcc(notString, unequal)
	patchJcc(stringMismatch, unequal)
	e.MovRegImm64(amd64.RAX, 0)
	doneJump := len(e.Code)
	e.JmpRel32(0)

	equal := len(e.Code)
	patchJcc(rawEqual, equal)
	patchJcc(bothZero, equal)
	e.MovRegImm64(amd64.RAX, 1)
	done := len(e.Code)
	patchJmp(doneJump, done)
	e.Ret()
}

func emitAMD64CollectionNew(e *amd64.Emitter, allocOffset int) {
	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.SubRegImm32(amd64.RSP, 40)
	e.MovRegImm64(amd64.RDI, int64(amd64CollectionPayload))
	callObj := len(e.Code)
	e.CallRel32(int32(allocOffset - (callObj + 5)))
	e.MovRegReg(amd64.RBX, amd64.RAX)
	emitAMD64SetObjectType(e, amd64.RBX, amd64ObjectTypeCollection)
	// Root collection while allocating entries.
	e.MovRegDeref(amd64.R10, amd64.R15, amd64RTRootHead)
	e.MovDerefReg(amd64.RSP, 0, amd64.R10)
	e.MovRegImm64(amd64.R10, 1)
	e.MovDerefReg(amd64.RSP, 8, amd64.R10)
	e.MovDerefReg(amd64.RSP, 16, amd64.RBX)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.RSP)
	e.MovRegImm64(amd64.RDI, 4*int64(amd64CollectionEntrySize))
	callEntries := len(e.Code)
	e.CallRel32(int32(allocOffset - (callEntries + 5)))
	emitAMD64SetObjectType(e, amd64.RAX, amd64ObjectTypeJSValueData)
	// Fresh bump/mmap memory is already zero; only reclaimed tables need clearing.
	e.TestRegReg(amd64.RDX, amd64.RDX)
	zeroFreshDone := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	// Clear 8 JSValue slots.
	e.MovRegReg(amd64.R10, amd64.RAX)
	e.MovRegImm64(amd64.R11, 8)
	e.MovRegImm64(amd64.RDX, 0)
	zeroLoop := len(e.Code)
	e.MovDerefReg(amd64.R10, 0, amd64.RDX)
	e.AddRegImm32(amd64.R10, 8)
	e.SubRegImm32(amd64.R11, 1)
	zeroBack := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	binary.LittleEndian.PutUint32(e.Code[zeroBack+2:], uint32(int32(zeroLoop-(zeroBack+6))))
	zeroFreshDoneLabel := len(e.Code)
	binary.LittleEndian.PutUint32(e.Code[zeroFreshDone+2:], uint32(int32(zeroFreshDoneLabel-(zeroFreshDone+6))))
	e.MovRegImm64(amd64.R10, 0)
	e.MovDerefReg(amd64.RBX, amd64CollectionCount, amd64.R10)
	e.MovRegImm64(amd64.R10, 4)
	e.MovDerefReg(amd64.RBX, amd64CollectionCapacity, amd64.R10)
	e.MovDerefReg(amd64.RBX, amd64CollectionEntries, amd64.RAX)
	e.MovRegDeref(amd64.R10, amd64.RSP, 0)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.R10)
	e.MovRegReg(amd64.RAX, amd64.RBX)
	e.AddRegImm32(amd64.RSP, 40)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}

// emitAMD64CollectionFind leaves index in RAX, or -1. It is emitted as a
// standalone helper: RDI=collection, RSI=boxed key.
func emitAMD64CollectionFind(e *amd64.Emitter, eqOffset int) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.MovRegReg(amd64.RBX, amd64.RDI)
	e.MovRegReg(amd64.R12, amd64.RSI)
	e.MovRegDeref(amd64.R13, amd64.RBX, amd64CollectionCount)
	e.MovRegImm64(amd64.R10, 0)
	loop := len(e.Code)
	e.CmpRegReg(amd64.R10, amd64.R13)
	miss := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegDeref(amd64.R11, amd64.RBX, amd64CollectionEntries)
	e.MovRegReg(amd64.RAX, amd64.R10)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.R11, amd64.RAX)
	e.MovRegDeref(amd64.RDI, amd64.R11, 0)
	e.MovRegReg(amd64.RSI, amd64.R12)
	e.Push(amd64.R10)
	call := len(e.Code)
	e.CallRel32(int32(eqOffset - (call + 5)))
	e.Pop(amd64.R10)
	e.TestRegReg(amd64.RAX, amd64.RAX)
	found := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.AddRegImm32(amd64.R10, 1)
	back := len(e.Code)
	e.JmpRel32(0)
	patchJmp(back, loop)
	foundLabel := len(e.Code)
	patchJcc(found, foundLabel)
	e.MovRegReg(amd64.RAX, amd64.R10)
	doneJump := len(e.Code)
	e.JmpRel32(0)
	missLabel := len(e.Code)
	patchJcc(miss, missLabel)
	e.MovRegImm64(amd64.RAX, -1)
	done := len(e.Code)
	patchJmp(doneJump, done)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Ret()
}

func emitAMD64CollectionSet(e *amd64.Emitter, allocOffset, findOffset int) {
	// RDI=collection, RSI=boxed key, RDX=boxed value. Return collection in RAX.
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }
	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	e.SubRegImm32(amd64.RSP, 48)
	e.MovRegReg(amd64.RBX, amd64.RDI)
	e.MovRegReg(amd64.R12, amd64.RSI)
	e.MovRegReg(amd64.R13, amd64.RDX)
	e.MovRegReg(amd64.RDI, amd64.RBX)
	e.MovRegReg(amd64.RSI, amd64.R12)
	callFind := len(e.Code)
	e.CallRel32(int32(findOffset - (callFind + 5)))
	e.CmpRegImm32(amd64.RAX, -1)
	newEntry := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	// Existing entry value update.
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64CollectionEntries)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.R10, amd64.RAX)
	e.MovDerefReg(amd64.R10, 8, amd64.R13)
	updateDone := len(e.Code)
	e.JmpRel32(0)

	addNew := len(e.Code)
	patchJcc(newEntry, addNew)
	e.MovRegDeref(amd64.R14, amd64.RBX, amd64CollectionCount)
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64CollectionCapacity)
	e.CmpRegReg(amd64.R14, amd64.R10)
	haveCap := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	// Root object + boxed key/value across growth allocation.
	e.MovRegDeref(amd64.R11, amd64.R15, amd64RTRootHead)
	e.MovDerefReg(amd64.RSP, 0, amd64.R11)
	e.MovRegImm64(amd64.R11, 3)
	e.MovDerefReg(amd64.RSP, 8, amd64.R11)
	e.MovDerefReg(amd64.RSP, 16, amd64.RBX)
	e.MovDerefReg(amd64.RSP, 24, amd64.R12)
	// Third precise root slot holds the boxed value.
	e.MovDerefReg(amd64.RSP, 32, amd64.R13)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.RSP)
	e.AddRegReg(amd64.R10, amd64.R10)
	e.MovRegReg(amd64.RDI, amd64.R10)
	e.AddRegReg(amd64.RDI, amd64.RDI)
	e.AddRegReg(amd64.RDI, amd64.RDI)
	e.AddRegReg(amd64.RDI, amd64.RDI)
	e.AddRegReg(amd64.RDI, amd64.RDI)
	callAlloc := len(e.Code)
	e.CallRel32(int32(allocOffset - (callAlloc + 5)))
	e.MovRegReg(amd64.R9, amd64.RAX)
	emitAMD64SetObjectType(e, amd64.R9, amd64ObjectTypeJSValueData)
	// Fresh tables are already zero; reclaimed tables must be scrubbed before GC sees them.
	e.TestRegReg(amd64.RDX, amd64.RDX)
	growZeroFreshDone := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	// Zero new table: capacity R10 was caller-clobbered, reload old cap and double.
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64CollectionCapacity)
	e.AddRegReg(amd64.R10, amd64.R10)
	e.MovRegReg(amd64.R8, amd64.R9)
	e.MovRegReg(amd64.R11, amd64.R10)
	e.AddRegReg(amd64.R11, amd64.R11)
	e.MovRegImm64(amd64.RAX, 0)
	zeroLoop := len(e.Code)
	e.MovDerefReg(amd64.R8, 0, amd64.RAX)
	e.AddRegImm32(amd64.R8, 8)
	e.SubRegImm32(amd64.R11, 1)
	zeroBack := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	patchJcc(zeroBack, zeroLoop)
	growZeroFreshDoneLabel := len(e.Code)
	patchJcc(growZeroFreshDone, growZeroFreshDoneLabel)
	// Capacity is needed below even when the clear was skipped.
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64CollectionCapacity)
	e.AddRegReg(amd64.R10, amd64.R10)
	// Copy used entries (count * 2 qwords).
	e.MovRegDeref(amd64.R8, amd64.RBX, amd64CollectionEntries)
	e.MovRegReg(amd64.R11, amd64.R14)
	e.AddRegReg(amd64.R11, amd64.R11)
	e.MovRegReg(amd64.RDX, amd64.R9)
	emitAMD64CopyQwords(e, amd64.RDX, amd64.R8, amd64.R11)
	e.MovDerefReg(amd64.RBX, amd64CollectionEntries, amd64.R9)
	e.MovDerefReg(amd64.RBX, amd64CollectionCapacity, amd64.R10)
	e.MovRegDeref(amd64.R11, amd64.RSP, 0)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.R11)
	capReady := len(e.Code)
	patchJcc(haveCap, capReady)
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64CollectionEntries)
	e.MovRegReg(amd64.RAX, amd64.R14)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.R10, amd64.RAX)
	e.MovDerefReg(amd64.R10, 0, amd64.R12)
	e.MovDerefReg(amd64.R10, 8, amd64.R13)
	e.AddRegImm32(amd64.R14, 1)
	e.MovDerefReg(amd64.RBX, amd64CollectionCount, amd64.R14)
	done := len(e.Code)
	patchJmp(updateDone, done)
	e.MovRegReg(amd64.RAX, amd64.RBX)
	e.AddRegImm32(amd64.RSP, 48)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}

func emitAMD64CollectionGet(e *amd64.Emitter, findOffset int) {
	// RDI=collection RSI=key. RAX=value or undefined; mirror bits into XMM0.
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.SubRegImm32(amd64.RSP, 8)
	e.MovRegReg(amd64.RBX, amd64.RDI)
	e.MovRegReg(amd64.R12, amd64.RSI)
	callFind := len(e.Code)
	e.CallRel32(int32(findOffset - (callFind + 5)))
	e.CmpRegImm32(amd64.RAX, -1)
	miss := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64CollectionEntries)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.R10, amd64.RAX)
	e.MovRegDeref(amd64.RAX, amd64.R10, 8)
	doneJump := len(e.Code)
	e.JmpRel32(0)
	missLabel := len(e.Code)
	binary.LittleEndian.PutUint32(e.Code[miss+2:], uint32(int32(missLabel-(miss+6))))
	e.MovRegImm64(amd64.RAX, amd64UndefinedBits)
	done := len(e.Code)
	binary.LittleEndian.PutUint32(e.Code[doneJump+1:], uint32(int32(done-(doneJump+5))))
	e.MovQXMMReg(amd64.XMM0, amd64.RAX)
	e.AddRegImm32(amd64.RSP, 8)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Ret()
}

func emitAMD64CollectionHas(e *amd64.Emitter, findOffset int) {
	e.SubRegImm32(amd64.RSP, 8)
	call := len(e.Code)
	e.CallRel32(int32(findOffset - (call + 5)))
	e.CmpRegImm32(amd64.RAX, -1)
	e.Setcc(amd64.CondNE, amd64.RAX)
	e.AddRegImm32(amd64.RSP, 8)
	e.Ret()
}

func emitAMD64CollectionDelete(e *amd64.Emitter, findOffset int) {
	// RDI=collection RSI=key. Stable delete by shifting following entries left.
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.SubRegImm32(amd64.RSP, 8)
	e.MovRegReg(amd64.RBX, amd64.RDI)
	e.MovRegReg(amd64.R12, amd64.RSI)
	call := len(e.Code)
	e.CallRel32(int32(findOffset - (call + 5)))
	e.CmpRegImm32(amd64.RAX, -1)
	miss := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64CollectionCount)
	e.SubRegImm32(amd64.R10, 1)
	e.MovRegDeref(amd64.R11, amd64.RBX, amd64CollectionEntries)
	e.MovRegReg(amd64.R12, amd64.RAX)
	loop := len(e.Code)
	e.CmpRegReg(amd64.R12, amd64.R10)
	doneShift := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	// dst = entries + idx*16; src = dst+16
	e.MovRegReg(amd64.RAX, amd64.R12)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.MovRegReg(amd64.RDI, amd64.R11)
	e.AddRegReg(amd64.RDI, amd64.RAX)
	e.MovRegDeref(amd64.RSI, amd64.RDI, 16)
	e.MovDerefReg(amd64.RDI, 0, amd64.RSI)
	e.MovRegDeref(amd64.RSI, amd64.RDI, 24)
	e.MovDerefReg(amd64.RDI, 8, amd64.RSI)
	e.AddRegImm32(amd64.R12, 1)
	back := len(e.Code)
	e.JmpRel32(0)
	patchJmp(back, loop)
	clearLast := len(e.Code)
	patchJcc(doneShift, clearLast)
	e.MovRegReg(amd64.RAX, amd64.R10)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.RAX, amd64.RAX)
	e.AddRegReg(amd64.R11, amd64.RAX)
	e.MovRegImm64(amd64.RAX, 0)
	e.MovDerefReg(amd64.R11, 0, amd64.RAX)
	e.MovDerefReg(amd64.R11, 8, amd64.RAX)
	e.MovDerefReg(amd64.RBX, amd64CollectionCount, amd64.R10)
	e.MovRegImm64(amd64.RAX, 1)
	doneJump := len(e.Code)
	e.JmpRel32(0)
	missLabel := len(e.Code)
	patchJcc(miss, missLabel)
	e.MovRegImm64(amd64.RAX, 0)
	done := len(e.Code)
	patchJmp(doneJump, done)
	e.AddRegImm32(amd64.RSP, 8)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Ret()
}

func emitAMD64CollectionClear(e *amd64.Emitter) {
	e.MovRegDeref(amd64.R10, amd64.RDI, amd64CollectionEntries)
	e.MovRegDeref(amd64.R11, amd64.RDI, amd64CollectionCapacity)
	e.AddRegReg(amd64.R11, amd64.R11)
	e.MovRegImm64(amd64.RAX, 0)
	loop := len(e.Code)
	e.MovDerefReg(amd64.R10, 0, amd64.RAX)
	e.AddRegImm32(amd64.R10, 8)
	e.SubRegImm32(amd64.R11, 1)
	back := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	binary.LittleEndian.PutUint32(e.Code[back+2:], uint32(int32(loop-(back+6))))
	e.MovRegImm64(amd64.RAX, 0)
	e.MovDerefReg(amd64.RDI, amd64CollectionCount, amd64.RAX)
	e.Ret()
}

func emitAMD64CollectionSize(e *amd64.Emitter) {
	e.MovRegDeref(amd64.RAX, amd64.RDI, amd64CollectionCount)
	e.Cvtsi2sd(amd64.XMM0, amd64.RAX)
	e.Ret()
}
