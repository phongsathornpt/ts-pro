package lower

import (
	"encoding/binary"

	"github.com/phongsathornpt/ts-pro/internal/backend/asm/amd64"
)

func emitAMD64UTF8Validate(e *amd64.Emitter) {
	patchJcc := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6))))
	}
	patchJmp := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5))))
	}
	var failJumps []int
	failIf := func(cond amd64.Cond) {
		at := len(e.Code)
		e.JccRel32(cond, 0)
		failJumps = append(failJumps, at)
	}

	e.Cvttsd2si(amd64.R8, amd64.XMM0)
	e.Cvttsd2si(amd64.R9, amd64.XMM1)
	e.MovRegDeref(amd64.R10, amd64.RDI, amd64ByteBufferData)
	e.AddRegReg(amd64.R10, amd64.R8)
	e.MovRegReg(amd64.R8, amd64.R10)

	loop := len(e.Code)
	e.TestRegReg(amd64.R9, amd64.R9)
	done := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovzxRegDeref8(amd64.R10, amd64.R8, 0)
	e.CmpRegImm32(amd64.R10, 0x80)
	ascii := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, 0xC2)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R10, 0xE0)
	two := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, 0xF0)
	three := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R10, 0xF5)
	four := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	failJump := len(e.Code)
	e.JmpRel32(0)

	asciiLabel := len(e.Code)
	patchJcc(ascii, asciiLabel)
	e.AddRegImm32(amd64.R8, 1)
	e.SubRegImm32(amd64.R9, 1)
	asciiBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(asciiBack, loop)

	twoLabel := len(e.Code)
	patchJcc(two, twoLabel)
	e.CmpRegImm32(amd64.R9, 2)
	failIf(amd64.CondB)
	e.MovzxRegDeref8(amd64.R11, amd64.R8, 1)
	e.CmpRegImm32(amd64.R11, 0x80)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R11, 0xBF)
	failIf(amd64.CondA)
	e.AddRegImm32(amd64.R8, 2)
	e.SubRegImm32(amd64.R9, 2)
	twoBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(twoBack, loop)

	threeLabel := len(e.Code)
	patchJcc(three, threeLabel)
	e.CmpRegImm32(amd64.R9, 3)
	failIf(amd64.CondB)
	e.MovzxRegDeref8(amd64.R11, amd64.R8, 1)
	e.CmpRegImm32(amd64.R10, 0xE0)
	threeNotE0 := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.CmpRegImm32(amd64.R11, 0xA0)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R11, 0xBF)
	failIf(amd64.CondA)
	threeSecondOK := len(e.Code)
	e.JmpRel32(0)

	threeNotE0Label := len(e.Code)
	patchJcc(threeNotE0, threeNotE0Label)
	e.CmpRegImm32(amd64.R10, 0xED)
	threeDefault := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.CmpRegImm32(amd64.R11, 0x80)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R11, 0x9F)
	failIf(amd64.CondA)
	threeEDDone := len(e.Code)
	e.JmpRel32(0)
	threeDefaultLabel := len(e.Code)
	patchJcc(threeDefault, threeDefaultLabel)
	e.CmpRegImm32(amd64.R11, 0x80)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R11, 0xBF)
	failIf(amd64.CondA)
	threeSecondDone := len(e.Code)
	patchJmp(threeSecondOK, threeSecondDone)
	patchJmp(threeEDDone, threeSecondDone)
	e.MovzxRegDeref8(amd64.R11, amd64.R8, 2)
	e.CmpRegImm32(amd64.R11, 0x80)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R11, 0xBF)
	failIf(amd64.CondA)
	e.AddRegImm32(amd64.R8, 3)
	e.SubRegImm32(amd64.R9, 3)
	threeBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(threeBack, loop)

	fourLabel := len(e.Code)
	patchJcc(four, fourLabel)
	e.CmpRegImm32(amd64.R9, 4)
	failIf(amd64.CondB)
	e.MovzxRegDeref8(amd64.R11, amd64.R8, 1)
	e.CmpRegImm32(amd64.R10, 0xF0)
	fourNotF0 := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.CmpRegImm32(amd64.R11, 0x90)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R11, 0xBF)
	failIf(amd64.CondA)
	fourSecondOK := len(e.Code)
	e.JmpRel32(0)
	fourNotF0Label := len(e.Code)
	patchJcc(fourNotF0, fourNotF0Label)
	e.CmpRegImm32(amd64.R10, 0xF4)
	fourDefault := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.CmpRegImm32(amd64.R11, 0x80)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R11, 0x8F)
	failIf(amd64.CondA)
	fourF4Done := len(e.Code)
	e.JmpRel32(0)

	fourDefaultLabel := len(e.Code)
	patchJcc(fourDefault, fourDefaultLabel)
	e.CmpRegImm32(amd64.R11, 0x80)
	failIf(amd64.CondB)
	e.CmpRegImm32(amd64.R11, 0xBF)
	failIf(amd64.CondA)
	fourSecondDone := len(e.Code)
	patchJmp(fourSecondOK, fourSecondDone)
	patchJmp(fourF4Done, fourSecondDone)
	for _, disp := range []int32{2, 3} {
		e.MovzxRegDeref8(amd64.R11, amd64.R8, disp)
		e.CmpRegImm32(amd64.R11, 0x80)
		failIf(amd64.CondB)
		e.CmpRegImm32(amd64.R11, 0xBF)
		failIf(amd64.CondA)
	}
	e.AddRegImm32(amd64.R8, 4)
	e.SubRegImm32(amd64.R9, 4)
	fourBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(fourBack, loop)

	doneLabel := len(e.Code)
	patchJcc(done, doneLabel)
	e.MovRegImm64(amd64.RAX, 1)
	e.Ret()
	failLabel := len(e.Code)
	patchJmp(failJump, failLabel)
	for _, at := range failJumps {
		patchJcc(at, failLabel)
	}
	e.MovRegImm64(amd64.RAX, 0)
	e.Ret()
}
