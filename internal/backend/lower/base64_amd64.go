func emitAMD64BtoaValid(e *amd64.Emitter) {
	patchJcc := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6))))
	}
	patchJmp := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5))))
	}
	e.MovRegReg(amd64.R8, amd64.RDI)
	e.AddRegImm32(amd64.R8, 8)
	e.MovRegDeref(amd64.R9, amd64.RDI, 0)
	e.AddRegReg(amd64.R9, amd64.R8)
	loop := len(e.Code)
	e.CmpRegReg(amd64.R8, amd64.R9)
	done := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovzxRegDeref8(amd64.RAX, amd64.R8, 0)
	e.CmpRegImm32(amd64.RAX, 128)
	ascii := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.RAX, 0xC2)
	c2 := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.CmpRegImm32(amd64.RAX, 0xC3)
	invalidLead := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	twoByte := len(e.Code)
	patchJcc(c2, twoByte)
	e.MovRegReg(amd64.R10, amd64.R8)
	e.AddRegImm32(amd64.R10, 1)
	e.CmpRegReg(amd64.R10, amd64.R9)
	missingContinuation := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovzxRegDeref8(amd64.R11, amd64.R8, 1)
	e.CmpRegImm32(amd64.R11, 0x80)
	badContinuationLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.R11, 0xBF)
	badContinuationHigh := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	e.AddRegImm32(amd64.R8, 2)
	twoBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(twoBack, loop)
	asciiLabel := len(e.Code)
	patchJcc(ascii, asciiLabel)
	e.AddRegImm32(amd64.R8, 1)
	asciiBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(asciiBack, loop)
	doneLabel := len(e.Code)
	patchJcc(done, doneLabel)
	e.MovRegImm64(amd64.RAX, 1)
	e.Ret()
	invalid := len(e.Code)
	patchJcc(invalidLead, invalid)
	patchJcc(missingContinuation, invalid)
	patchJcc(badContinuationLow, invalid)
	patchJcc(badContinuationHigh, invalid)
	e.MovRegImm64(amd64.RAX, 0)
	e.Ret()
}

func emitAMD64Latin1Next(e *amd64.Emitter) {
	e.MovzxRegDeref8(amd64.RAX, amd64.RDI, 0)
	e.CmpRegImm32(amd64.RAX, 128)
	ascii := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.MovRegImm64(amd64.R10, 0x1F)
	e.AndRegReg(amd64.RAX, amd64.R10)
	e.MovRegImm64(amd64.R10, 64)
	e.ImulRegReg(amd64.RAX, amd64.R10)
	e.MovzxRegDeref8(amd64.R10, amd64.RDI, 1)
	e.MovRegImm64(amd64.R11, 0x3F)
	e.AndRegReg(amd64.R10, amd64.R11)
	e.AddRegReg(amd64.RAX, amd64.R10)
	e.MovRegReg(amd64.RDX, amd64.RDI)
	e.AddRegImm32(amd64.RDX, 2)
	e.Ret()
	asciiLabel := len(e.Code)
	binary.LittleEndian.PutUint32(e.Code[ascii+2:], uint32(int32(asciiLabel-(ascii+6))))
	e.MovRegReg(amd64.RDX, amd64.RDI)
	e.AddRegImm32(amd64.RDX, 1)
	e.Ret()
}

func emitAMD64Base64Char(e *amd64.Emitter) {
	patchJcc := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6))))
	}
	e.MovRegReg(amd64.RAX, amd64.RDI)
	e.CmpRegImm32(amd64.RAX, 25)
	upper := len(e.Code)
	e.JccRel32(amd64.CondBE, 0)
	e.CmpRegImm32(amd64.RAX, 51)
	lower := len(e.Code)
	e.JccRel32(amd64.CondBE, 0)
	e.CmpRegImm32(amd64.RAX, 61)
	digit := len(e.Code)
	e.JccRel32(amd64.CondBE, 0)
	e.CmpRegImm32(amd64.RAX, 62)
	plus := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovRegImm64(amd64.RAX, '/')
	e.Ret()
	upperLabel := len(e.Code)
	patchJcc(upper, upperLabel)
	e.AddRegImm32(amd64.RAX, 'A')
	e.Ret()
	lowerLabel := len(e.Code)
	patchJcc(lower, lowerLabel)
	e.SubRegImm32(amd64.RAX, 26)
	e.AddRegImm32(amd64.RAX, 'a')
	e.Ret()
	digitLabel := len(e.Code)
	patchJcc(digit, digitLabel)
	e.SubRegImm32(amd64.RAX, 52)
	e.AddRegImm32(amd64.RAX, '0')
	e.Ret()
	plusLabel := len(e.Code)
	patchJcc(plus, plusLabel)
	e.MovRegImm64(amd64.RAX, '+')
	e.Ret()
}

func emitAMD64Btoa(e *amd64.Emitter, allocOffset, nextOffset, charOffset int) {
	patchJcc := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6))))
	}
	patchJmp := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5))))
	}
	call := func(target int) {
		at := len(e.Code)
		e.CallRel32(int32(target - (at + 5)))
	}
	emitChar := func() {
		call(charOffset)
		e.MovDerefReg8(amd64.R13, 0, amd64.RAX)
		e.AddRegImm32(amd64.R13, 1)
	}
	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	e.SubRegImm32(amd64.RSP, 16)
	e.MovRegReg(amd64.RBX, amd64.RDI)
	// Count Latin-1 code points after validation.
	e.MovRegReg(amd64.R12, amd64.RBX)
	e.AddRegImm32(amd64.R12, 8)
	e.MovRegDeref(amd64.R14, amd64.RBX, 0)
	e.AddRegReg(amd64.R14, amd64.R12)
	e.MovRegImm64(amd64.R13, 0)
	countLoop := len(e.Code)
	e.CmpRegReg(amd64.R12, amd64.R14)
	countDone := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovzxRegDeref8(amd64.RAX, amd64.R12, 0)
	e.CmpRegImm32(amd64.RAX, 128)
	countASCII := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.AddRegImm32(amd64.R12, 2)
	countAdvance := len(e.Code)
	e.JmpRel32(0)
	countASCIILabel := len(e.Code)
	patchJcc(countASCII, countASCIILabel)
	e.AddRegImm32(amd64.R12, 1)
	countAdvanceLabel := len(e.Code)
	patchJmp(countAdvance, countAdvanceLabel)
	e.AddRegImm32(amd64.R13, 1)
	countBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(countBack, countLoop)
	countDoneLabel := len(e.Code)
	patchJcc(countDone, countDoneLabel)
	e.MovRegReg(amd64.RAX, amd64.R13)
	e.AddRegImm32(amd64.RAX, 2)
	e.Cqo()
	e.MovRegImm64(amd64.R10, 3)
	e.IdivReg(amd64.R10)
	e.MovRegImm64(amd64.R10, 4)
	e.ImulRegReg(amd64.RAX, amd64.R10)
	e.MovDerefReg(amd64.RSP, 8, amd64.RAX)
	e.MovRegReg(amd64.RDI, amd64.RAX)
	e.AddRegImm32(amd64.RDI, 8)
	call(allocOffset)
	e.MovDerefReg(amd64.RSP, 0, amd64.RAX)
	e.MovRegDeref(amd64.R10, amd64.RSP, 8)
	e.MovDerefReg(amd64.RAX, 0, amd64.R10)
	e.MovRegReg(amd64.R13, amd64.RAX)
	e.AddRegImm32(amd64.R13, 8)
	e.MovRegReg(amd64.R12, amd64.RBX)
	e.AddRegImm32(amd64.R12, 8)
	e.MovRegDeref(amd64.R14, amd64.RBX, 0)
	e.AddRegReg(amd64.R14, amd64.R12)
	groupLoop := len(e.Code)
	e.CmpRegReg(amd64.R12, amd64.R14)
	encodeDone := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.RDI, amd64.R12)
	call(nextOffset)
	e.MovRegReg(amd64.R8, amd64.RAX)
	e.MovRegReg(amd64.R12, amd64.RDX)
	e.CmpRegReg(amd64.R12, amd64.R14)
	tailOne := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.RDI, amd64.R12)
	call(nextOffset)
	e.MovRegReg(amd64.R9, amd64.RAX)
	e.MovRegReg(amd64.R12, amd64.RDX)
	e.CmpRegReg(amd64.R12, amd64.R14)
	tailTwo := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.RDI, amd64.R12)
	call(nextOffset)
	e.MovRegReg(amd64.R10, amd64.RAX)
	e.MovRegReg(amd64.R12, amd64.RDX)

	e.MovRegReg(amd64.RDI, amd64.R8)
	e.ShrRegImm8(amd64.RDI, 2)
	emitChar()
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.MovRegImm64(amd64.R11, 3)
	e.AndRegReg(amd64.RDI, amd64.R11)
	e.MovRegImm64(amd64.R11, 16)
	e.ImulRegReg(amd64.RDI, amd64.R11)
	e.MovRegReg(amd64.RAX, amd64.R9)
	e.ShrRegImm8(amd64.RAX, 4)
	e.AddRegReg(amd64.RDI, amd64.RAX)
	emitChar()
	e.MovRegReg(amd64.RDI, amd64.R9)
	e.MovRegImm64(amd64.R11, 15)
	e.AndRegReg(amd64.RDI, amd64.R11)
	e.MovRegImm64(amd64.R11, 4)
	e.ImulRegReg(amd64.RDI, amd64.R11)
	e.MovRegReg(amd64.RAX, amd64.R10)
	e.ShrRegImm8(amd64.RAX, 6)
	e.AddRegReg(amd64.RDI, amd64.RAX)
	emitChar()
	e.MovRegReg(amd64.RDI, amd64.R10)
	e.MovRegImm64(amd64.R11, 63)
	e.AndRegReg(amd64.RDI, amd64.R11)
	emitChar()
	groupBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(groupBack, groupLoop)

	tailTwoLabel := len(e.Code)
	patchJcc(tailTwo, tailTwoLabel)
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.ShrRegImm8(amd64.RDI, 2)
	emitChar()
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.MovRegImm64(amd64.R11, 3)
	e.AndRegReg(amd64.RDI, amd64.R11)
	e.MovRegImm64(amd64.R11, 16)
	e.ImulRegReg(amd64.RDI, amd64.R11)
	e.MovRegReg(amd64.RAX, amd64.R9)
	e.ShrRegImm8(amd64.RAX, 4)
	e.AddRegReg(amd64.RDI, amd64.RAX)
	emitChar()
	e.MovRegReg(amd64.RDI, amd64.R9)
	e.MovRegImm64(amd64.R11, 15)
	e.AndRegReg(amd64.RDI, amd64.R11)
	e.MovRegImm64(amd64.R11, 4)
	e.ImulRegReg(amd64.RDI, amd64.R11)
	emitChar()
	e.MovRegImm64(amd64.RAX, 61)
	e.MovDerefReg8(amd64.R13, 0, amd64.RAX)
	e.AddRegImm32(amd64.R13, 1)
	tailTwoDone := len(e.Code)
	e.JmpRel32(0)
	tailOneLabel := len(e.Code)
	patchJcc(tailOne, tailOneLabel)
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.ShrRegImm8(amd64.RDI, 2)
	emitChar()
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.MovRegImm64(amd64.R11, 3)
	e.AndRegReg(amd64.RDI, amd64.R11)
	e.MovRegImm64(amd64.R11, 16)
	e.ImulRegReg(amd64.RDI, amd64.R11)
	emitChar()
	e.MovRegImm64(amd64.RAX, 61)
	e.MovDerefReg8(amd64.R13, 0, amd64.RAX)
	e.AddRegImm32(amd64.R13, 1)
	e.MovDerefReg8(amd64.R13, 0, amd64.RAX)
	e.AddRegImm32(amd64.R13, 1)
	finish := len(e.Code)
	patchJmp(tailTwoDone, finish)
	encodeDoneLabel := len(e.Code)
	patchJcc(encodeDone, encodeDoneLabel)
	e.MovRegDeref(amd64.RAX, amd64.RSP, 0)
	e.AddRegImm32(amd64.RSP, 16)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}
