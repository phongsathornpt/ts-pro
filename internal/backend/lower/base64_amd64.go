func emitAMD64AtobValid(e *amd64.Emitter, whitespaceOffset, valueOffset int) {
	patchJcc := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6))))
	}
	patchJmp := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5))))
	}
	call := func(target int) {
		at := len(e.Code)
		e.CallRel32(int32(target - (at + 5)))
	}
	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	e.MovRegReg(amd64.R12, amd64.RDI)
	e.AddRegImm32(amd64.R12, 8)
	e.MovRegDeref(amd64.R13, amd64.RDI, 0)
	e.AddRegReg(amd64.R13, amd64.R12)
	e.MovRegImm64(amd64.RBX, 0)
	e.MovRegImm64(amd64.R14, 0)
	e.MovRegImm64(amd64.R8, 0)
	loop := len(e.Code)
	e.CmpRegReg(amd64.R12, amd64.R13)
	done := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovzxRegDeref8(amd64.R11, amd64.R12, 0)
	e.AddRegImm32(amd64.R12, 1)
	e.MovRegReg(amd64.RDI, amd64.R11)
	call(whitespaceOffset)
	e.TestRegReg(amd64.RAX, amd64.RAX)
	skipWhitespace := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.AddRegImm32(amd64.RBX, 1)
	e.CmpRegImm32(amd64.R11, 61)
	padding := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.TestRegReg(amd64.R8, amd64.R8)
	dataAfterPadding := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.MovRegReg(amd64.RDI, amd64.R11)
	call(valueOffset)
	e.CmpRegImm32(amd64.RAX, 0)
	invalidValue := len(e.Code)
	e.JccRel32(amd64.CondL, 0)
	back := len(e.Code)
	e.JmpRel32(0)
	paddingLabel := len(e.Code)
	patchJcc(padding, paddingLabel)
	e.MovRegImm64(amd64.R8, 1)
	e.AddRegImm32(amd64.R14, 1)
	e.CmpRegImm32(amd64.R14, 2)
	tooMuchPadding := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	paddingBack := len(e.Code)
	e.JmpRel32(0)
	skipLabel := len(e.Code)
	patchJcc(skipWhitespace, skipLabel)
	skipBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(back, loop)
	patchJmp(paddingBack, loop)
	patchJmp(skipBack, loop)
	doneLabel := len(e.Code)
	patchJcc(done, doneLabel)
	e.MovRegReg(amd64.RAX, amd64.RBX)
	e.Cqo()
	e.MovRegImm64(amd64.R10, 4)
	e.IdivReg(amd64.R10)
	e.CmpRegImm32(amd64.RDX, 1)
	badRemainder := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.TestRegReg(amd64.R14, amd64.R14)
	valid := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.TestRegReg(amd64.RDX, amd64.RDX)
	paddingRemainder := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	validLabel := len(e.Code)
	patchJcc(valid, validLabel)
	e.MovRegImm64(amd64.RAX, 1)
	finish := len(e.Code)
	e.JmpRel32(0)
	invalid := len(e.Code)
	patchJcc(dataAfterPadding, invalid)
	patchJcc(invalidValue, invalid)
	patchJcc(tooMuchPadding, invalid)
	patchJcc(badRemainder, invalid)
	patchJcc(paddingRemainder, invalid)
	e.MovRegImm64(amd64.RAX, 0)
	finishLabel := len(e.Code)
	patchJmp(finish, finishLabel)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}

func emitAMD64Latin1WriteUTF8(e *amd64.Emitter) {
	patchJcc := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6))))
	}
	e.CmpRegImm32(amd64.RDI, 128)
	ascii := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.MovRegReg(amd64.RAX, amd64.RDI)
	e.ShrRegImm8(amd64.RAX, 6)
	e.MovRegImm64(amd64.R10, 0xC0)
	e.OrRegReg(amd64.RAX, amd64.R10)
	e.MovDerefReg8(amd64.RSI, 0, amd64.RAX)
	e.MovRegReg(amd64.RAX, amd64.RDI)
	e.MovRegImm64(amd64.R10, 0x3F)
	e.AndRegReg(amd64.RAX, amd64.R10)
	e.MovRegImm64(amd64.R10, 0x80)
	e.OrRegReg(amd64.RAX, amd64.R10)
	e.MovDerefReg8(amd64.RSI, 1, amd64.RAX)
	e.MovRegReg(amd64.RAX, amd64.RSI)
	e.AddRegImm32(amd64.RAX, 2)
	e.Ret()
	asciiLabel := len(e.Code)
	patchJcc(ascii, asciiLabel)
	e.MovDerefReg8(amd64.RSI, 0, amd64.RDI)
	e.MovRegReg(amd64.RAX, amd64.RSI)
	e.AddRegImm32(amd64.RAX, 1)
	e.Ret()
}

func emitAMD64Atob(e *amd64.Emitter, allocOffset, whitespaceOffset, valueOffset, writeOffset int) {
	patchJcc := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6))))
	}
	patchJmp := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5))))
	}
	call := func(target int) {
		at := len(e.Code)
		e.CallRel32(int32(target - (at + 5)))
	}
	writeByte := func() {
		e.MovRegReg(amd64.RSI, amd64.R13)
		call(writeOffset)
		e.MovRegReg(amd64.R13, amd64.RAX)
	}
	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	e.SubRegImm32(amd64.RSP, 16)
	e.MovRegReg(amd64.RBX, amd64.RDI)
	// Count non-whitespace, non-padding base64 characters.
	e.MovRegReg(amd64.R12, amd64.RBX)
	e.AddRegImm32(amd64.R12, 8)
	e.MovRegDeref(amd64.R14, amd64.RBX, 0)
	e.AddRegReg(amd64.R14, amd64.R12)
	e.MovRegImm64(amd64.R13, 0)
	countLoop := len(e.Code)
	e.CmpRegReg(amd64.R12, amd64.R14)
	countDone := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovzxRegDeref8(amd64.R11, amd64.R12, 0)
	e.AddRegImm32(amd64.R12, 1)
	e.MovRegReg(amd64.RDI, amd64.R11)
	call(whitespaceOffset)
	e.TestRegReg(amd64.RAX, amd64.RAX)
	countSkip := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.CmpRegImm32(amd64.R11, 61)
	countPadding := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.AddRegImm32(amd64.R13, 1)
	countBack := len(e.Code)
	e.JmpRel32(0)
	countSkipLabel := len(e.Code)
	patchJcc(countSkip, countSkipLabel)
	patchJcc(countPadding, countSkipLabel)
	countSkipBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(countBack, countLoop)
	patchJmp(countSkipBack, countLoop)
	countDoneLabel := len(e.Code)
	patchJcc(countDone, countDoneLabel)
	// decodedBytes = floor(dataChars * 3 / 4), reserve 2x for UTF-8.
	e.MovRegReg(amd64.RAX, amd64.R13)
	e.MovRegImm64(amd64.R10, 3)
	e.ImulRegReg(amd64.RAX, amd64.R10)
	e.Cqo()
	e.MovRegImm64(amd64.R10, 4)
	e.IdivReg(amd64.R10)
	e.MovRegImm64(amd64.R10, 2)
	e.ImulRegReg(amd64.RAX, amd64.R10)
	e.MovRegReg(amd64.RDI, amd64.RAX)
	e.AddRegImm32(amd64.RDI, 8)
	call(allocOffset)
	e.MovDerefReg(amd64.RSP, 0, amd64.RAX)
	e.MovRegReg(amd64.R13, amd64.RAX)
	e.AddRegImm32(amd64.R13, 8)
	e.MovRegReg(amd64.R12, amd64.RBX)
	e.AddRegImm32(amd64.R12, 8)
	e.MovRegDeref(amd64.R14, amd64.RBX, 0)
	e.AddRegReg(amd64.R14, amd64.R12)
	e.MovRegImm64(amd64.R8, 0)
	e.MovRegImm64(amd64.R9, 0)
	decodeLoop := len(e.Code)
	e.CmpRegReg(amd64.R12, amd64.R14)
	decodeDone := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovzxRegDeref8(amd64.R11, amd64.R12, 0)
	e.AddRegImm32(amd64.R12, 1)
	e.MovRegReg(amd64.RDI, amd64.R11)
	call(whitespaceOffset)
	e.TestRegReg(amd64.RAX, amd64.RAX)
	decodeSkip := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.CmpRegImm32(amd64.R11, 61)
	decodePadding := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.MovRegReg(amd64.RDI, amd64.R11)
	call(valueOffset)
	e.MovRegImm64(amd64.R10, 64)
	e.ImulRegReg(amd64.R8, amd64.R10)
	e.AddRegReg(amd64.R8, amd64.RAX)
	e.AddRegImm32(amd64.R9, 1)
	e.CmpRegImm32(amd64.R9, 4)
	decodeContinue := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.ShrRegImm8(amd64.RDI, 16)
	e.MovRegImm64(amd64.R10, 255)
	e.AndRegReg(amd64.RDI, amd64.R10)
	writeByte()
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.ShrRegImm8(amd64.RDI, 8)
	e.MovRegImm64(amd64.R10, 255)
	e.AndRegReg(amd64.RDI, amd64.R10)
	writeByte()
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.MovRegImm64(amd64.R10, 255)
	e.AndRegReg(amd64.RDI, amd64.R10)
	writeByte()
	e.MovRegImm64(amd64.R8, 0)
	e.MovRegImm64(amd64.R9, 0)
	groupBack := len(e.Code)
	e.JmpRel32(0)
	decodeContinueLabel := len(e.Code)
	patchJcc(decodeContinue, decodeContinueLabel)
	continueBack := len(e.Code)
	e.JmpRel32(0)
	decodeSkipLabel := len(e.Code)
	patchJcc(decodeSkip, decodeSkipLabel)
	patchJcc(decodePadding, decodeSkipLabel)
	skipBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(groupBack, decodeLoop)
	patchJmp(continueBack, decodeLoop)
	patchJmp(skipBack, decodeLoop)
	decodeDoneLabel := len(e.Code)
	patchJcc(decodeDone, decodeDoneLabel)
	e.CmpRegImm32(amd64.R9, 2)
	tailTwo := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.CmpRegImm32(amd64.R9, 3)
	tailThree := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	finalize := len(e.Code)
	e.JmpRel32(0)
	tailTwoLabel := len(e.Code)
	patchJcc(tailTwo, tailTwoLabel)
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.ShrRegImm8(amd64.RDI, 4)
	e.MovRegImm64(amd64.R10, 255)
	e.AndRegReg(amd64.RDI, amd64.R10)
	writeByte()
	tailTwoDone := len(e.Code)
	e.JmpRel32(0)
	tailThreeLabel := len(e.Code)
	patchJcc(tailThree, tailThreeLabel)
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.ShrRegImm8(amd64.RDI, 10)
	e.MovRegImm64(amd64.R10, 255)
	e.AndRegReg(amd64.RDI, amd64.R10)
	writeByte()
	e.MovRegReg(amd64.RDI, amd64.R8)
	e.ShrRegImm8(amd64.RDI, 2)
	e.MovRegImm64(amd64.R10, 255)
	e.AndRegReg(amd64.RDI, amd64.R10)
	writeByte()
	tailThreeDone := len(e.Code)
	e.JmpRel32(0)
	finalizeLabel := len(e.Code)
	patchJmp(finalize, finalizeLabel)
	patchJmp(tailTwoDone, finalizeLabel)
	patchJmp(tailThreeDone, finalizeLabel)
	e.MovRegDeref(amd64.RAX, amd64.RSP, 0)
	e.MovRegReg(amd64.R10, amd64.RAX)
	e.AddRegImm32(amd64.R10, 8)
	e.MovRegReg(amd64.R11, amd64.R13)
	e.SubRegReg(amd64.R11, amd64.R10)
	e.MovDerefReg(amd64.RAX, 0, amd64.R11)
	e.AddRegImm32(amd64.RSP, 16)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}
