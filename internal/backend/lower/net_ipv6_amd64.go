package lower

import (
	"encoding/binary"

	"github.com/phongsathornpt/ts-pro/internal/backend/asm/amd64"
)

// emitAMD64NetParseIPv6 parses a bracketed IPv6 literal (for example [::1] or
// [2001:db8::1]) into a 16-byte address buffer. It supports one :: compression
// run and 1-4 hexadecimal digits per group. IPv4-embedded tails are deliberately
// left for a later parser extension. Failure returns an empty ByteBuffer.
//
// ABI: RDI=bracketed host string -> RAX=16-byte address ByteBuffer.
func emitAMD64NetParseIPv6(e *amd64.Emitter, byteBufferNewOffset int) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }

	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	// 0..63 parsed words, 64..127 expanded words.
	e.SubRegImm32(amd64.RSP, 160)
	e.MovRegReg(amd64.R12, amd64.RDI)

	var invalid []int
	// Validate brackets and minimum "[::]" size.
	e.MovRegDeref(amd64.R8, amd64.R12, 0)
	e.CmpRegImm32(amd64.R8, 4)
	tooShort := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	invalid = append(invalid, tooShort)
	e.MovzxRegDeref8(amd64.R10, amd64.R12, 8)
	e.CmpRegImm32(amd64.R10, '[')
	badOpen := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	invalid = append(invalid, badOpen)
	e.MovRegReg(amd64.R11, amd64.R12)
	e.AddRegImm32(amd64.R11, 8)
	e.AddRegReg(amd64.R11, amd64.R8)
	e.SubRegImm32(amd64.R11, 1)
	e.MovzxRegDeref8(amd64.R10, amd64.R11, 0)
	e.CmpRegImm32(amd64.R10, ']')
	badClose := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	invalid = append(invalid, badClose)

	// R9=string index, R10=current word, RBX=digit count,
	// R13=parsed group count, R14=compression index (-1 means absent).
	e.MovRegImm64(amd64.R9, 1)
	e.MovRegImm64(amd64.R10, 0)
	e.MovRegImm64(amd64.RBX, 0)
	e.MovRegImm64(amd64.R13, 0)
	e.MovRegImm64(amd64.R14, -1)

	parseLoop := len(e.Code)
	e.MovRegDeref(amd64.R8, amd64.R12, 0)
	e.SubRegImm32(amd64.R8, 1) // interior end, index of ']'
	e.CmpRegReg(amd64.R9, amd64.R8)
	parseDone := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.R11, amd64.R12)
	e.AddRegImm32(amd64.R11, 8)
	e.AddRegReg(amd64.R11, amd64.R9)
	e.MovzxRegDeref8(amd64.RAX, amd64.R11, 0)
	e.CmpRegImm32(amd64.RAX, ':')
	colon := len(e.Code)
	e.JccRel32(amd64.CondE, 0)

	// Hex nibble conversion.
	e.CmpRegImm32(amd64.RAX, '0')
	badHexLow := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.RAX, '9')
	hex09 := len(e.Code)
	e.JccRel32(amd64.CondBE, 0)
	e.CmpRegImm32(amd64.RAX, 'A')
	belowA := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.RAX, 'F')
	hexAF := len(e.Code)
	e.JccRel32(amd64.CondBE, 0)
	e.CmpRegImm32(amd64.RAX, 'a')
	belowa := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegImm32(amd64.RAX, 'f')
	hexaf := len(e.Code)
	e.JccRel32(amd64.CondBE, 0)
	badHex := len(e.Code)
	e.JmpRel32(0)

	hex09Label := len(e.Code)
	patchJcc(hex09, hex09Label)
	e.SubRegImm32(amd64.RAX, '0')
	hexReady09 := len(e.Code)
	e.JmpRel32(0)
	hexAFLabel := len(e.Code)
	patchJcc(hexAF, hexAFLabel)
	e.SubRegImm32(amd64.RAX, 'A'-10)
	hexReadyAF := len(e.Code)
	e.JmpRel32(0)
	hexafLabel := len(e.Code)
	patchJcc(hexaf, hexafLabel)
	e.SubRegImm32(amd64.RAX, 'a'-10)
	hexReady := len(e.Code)
	patchJmp(hexReady09, hexReady)
	patchJmp(hexReadyAF, hexReady)
	e.MovRegImm64(amd64.R11, 16)
	e.ImulRegReg(amd64.R10, amd64.R11)
	e.AddRegReg(amd64.R10, amd64.RAX)
	e.AddRegImm32(amd64.RBX, 1)
	e.CmpRegImm32(amd64.RBX, 4)
	tooManyDigits := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	invalid = append(invalid, tooManyDigits)
	e.AddRegImm32(amd64.R9, 1)
	hexBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(hexBack, parseLoop)

	colonLabel := len(e.Code)
	patchJcc(colon, colonLabel)
	// R8 becomes a transient "had digits" flag here.
	e.MovRegImm64(amd64.R8, 0)
	e.TestRegReg(amd64.RBX, amd64.RBX)
	noWordBeforeColon := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	// Commit current group.
	e.CmpRegImm32(amd64.R13, 8)
	tooManyGroups1 := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	invalid = append(invalid, tooManyGroups1)
	e.MovRegReg(amd64.R11, amd64.R13)
	e.MovRegImm64(amd64.RAX, 8)
	e.ImulRegReg(amd64.R11, amd64.RAX)
	e.AddRegReg(amd64.R11, amd64.RSP)
	e.MovDerefReg(amd64.R11, 0, amd64.R10)
	e.AddRegImm32(amd64.R13, 1)
	e.MovRegImm64(amd64.R10, 0)
	e.MovRegImm64(amd64.RBX, 0)
	e.MovRegImm64(amd64.R8, 1)
	checkDouble := len(e.Code)
	patchJcc(noWordBeforeColon, checkDouble)

	// Look ahead for :: compression.
	e.MovRegDeref(amd64.R11, amd64.R12, 0)
	e.SubRegImm32(amd64.R11, 1)
	e.MovRegReg(amd64.RAX, amd64.R9)
	e.AddRegImm32(amd64.RAX, 1)
	e.CmpRegReg(amd64.RAX, amd64.R11)
	noSecondColon := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.R11, amd64.R12)
	e.AddRegImm32(amd64.R11, 8)
	e.AddRegReg(amd64.R11, amd64.RAX)
	e.MovzxRegDeref8(amd64.R11, amd64.R11, 0)
	e.CmpRegImm32(amd64.R11, ':')
	notDoubleColon := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	// Compression may occur only once.
	e.CmpRegImm32(amd64.R14, -1)
	secondCompression := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	invalid = append(invalid, secondCompression)
	e.MovRegReg(amd64.R14, amd64.R13)
	e.AddRegImm32(amd64.R9, 2)
	doubleBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(doubleBack, parseLoop)

	singleColon := len(e.Code)
	patchJcc(noSecondColon, singleColon)
	patchJcc(notDoubleColon, singleColon)
	// A single colon requires a group immediately before it.
	e.TestRegReg(amd64.R8, amd64.R8)
	emptySingleColon := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	invalid = append(invalid, emptySingleColon)
	e.AddRegImm32(amd64.R9, 1)
	singleBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(singleBack, parseLoop)

	parseDoneLabel := len(e.Code)
	patchJcc(parseDone, parseDoneLabel)
	// Commit trailing group, if any. An empty trailing group is valid only after ::.
	e.TestRegReg(amd64.RBX, amd64.RBX)
	noTrailingWord := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.CmpRegImm32(amd64.R13, 8)
	tooManyGroups2 := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	invalid = append(invalid, tooManyGroups2)
	e.MovRegReg(amd64.R11, amd64.R13)
	e.MovRegImm64(amd64.RAX, 8)
	e.ImulRegReg(amd64.R11, amd64.RAX)
	e.AddRegReg(amd64.R11, amd64.RSP)
	e.MovDerefReg(amd64.R11, 0, amd64.R10)
	e.AddRegImm32(amd64.R13, 1)
	validateGroups := len(e.Code)
	patchJcc(noTrailingWord, validateGroups)

	// Without compression exactly eight groups are required. With compression,
	// fewer than eight parsed groups are required so :: expands to at least one 0.
	e.CmpRegImm32(amd64.R14, -1)
	hasCompression := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.CmpRegImm32(amd64.R13, 8)
	wrongFullCount := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	invalid = append(invalid, wrongFullCount)
	e.MovRegImm64(amd64.R14, 8) // normalize no-compression expansion boundary
	groupsReadyJump := len(e.Code)
	e.JmpRel32(0)
	hasCompressionLabel := len(e.Code)
	patchJcc(hasCompression, hasCompressionLabel)
	e.CmpRegImm32(amd64.R13, 8)
	compressionNoRoom := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	invalid = append(invalid, compressionNoRoom)
	groupsReady := len(e.Code)
	patchJmp(groupsReadyJump, groupsReady)

	// Expand parsed groups into 8 words at rsp+64. zeroCount = 8-groupCount.
	e.MovRegImm64(amd64.R8, 8)
	e.SubRegReg(amd64.R8, amd64.R13) // zero count
	e.MovRegReg(amd64.R10, amd64.R14)
	e.AddRegReg(amd64.R10, amd64.R8) // compression end
	e.MovRegImm64(amd64.R9, 0)       // output word index
	expandLoop := len(e.Code)
	e.CmpRegImm32(amd64.R9, 8)
	expandDone := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.CmpRegReg(amd64.R9, amd64.R14)
	beforeCompression := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.CmpRegReg(amd64.R9, amd64.R10)
	insideCompression := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	// Source index = output-zeroCount after compression.
	e.MovRegReg(amd64.RAX, amd64.R9)
	e.SubRegReg(amd64.RAX, amd64.R8)
	afterSourceJump := len(e.Code)
	e.JmpRel32(0)
	beforeCompressionLabel := len(e.Code)
	patchJcc(beforeCompression, beforeCompressionLabel)
	e.MovRegReg(amd64.RAX, amd64.R9)
	beforeSourceJump := len(e.Code)
	e.JmpRel32(0)
	insideCompressionLabel := len(e.Code)
	patchJcc(insideCompression, insideCompressionLabel)
	e.MovRegImm64(amd64.R11, 0)
	zeroStoreJump := len(e.Code)
	e.JmpRel32(0)

	sourceReady := len(e.Code)
	patchJmp(afterSourceJump, sourceReady)
	patchJmp(beforeSourceJump, sourceReady)
	e.MovRegImm64(amd64.R11, 8)
	e.ImulRegReg(amd64.RAX, amd64.R11)
	e.AddRegReg(amd64.RAX, amd64.RSP)
	e.MovRegDeref(amd64.R11, amd64.RAX, 0)
	storeExpanded := len(e.Code)
	patchJmp(zeroStoreJump, storeExpanded)
	e.MovRegReg(amd64.RAX, amd64.R9)
	e.MovRegImm64(amd64.RBX, 8)
	e.ImulRegReg(amd64.RAX, amd64.RBX)
	e.AddRegImm32(amd64.RAX, 64)
	e.AddRegReg(amd64.RAX, amd64.RSP)
	e.MovDerefReg(amd64.RAX, 0, amd64.R11)
	e.AddRegImm32(amd64.R9, 1)
	expandBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(expandBack, expandLoop)
	expandDoneLabel := len(e.Code)
	patchJcc(expandDone, expandDoneLabel)

	// Allocate and serialize words in network byte order.
	e.MovRegImm64(amd64.R10, 16)
	e.Cvtsi2sd(amd64.XMM0, amd64.R10)
	callResult := len(e.Code)
	e.CallRel32(int32(byteBufferNewOffset - (callResult + 5)))
	e.MovRegReg(amd64.R12, amd64.RAX)
	e.MovRegDeref(amd64.R13, amd64.R12, amd64ByteBufferData)
	for i := 0; i < 8; i++ {
		e.MovRegDeref(amd64.R10, amd64.RSP, int32(64+i*8))
		e.MovRegReg(amd64.R11, amd64.R10)
		e.ShrRegImm8(amd64.R11, 8)
		e.MovRegImm64(amd64.RAX, 255)
		e.AndRegReg(amd64.R11, amd64.RAX)
		e.MovDerefReg8(amd64.R13, int32(i*2), amd64.R11)
		e.AndRegReg(amd64.R10, amd64.RAX)
		e.MovDerefReg8(amd64.R13, int32(i*2+1), amd64.R10)
	}
	e.MovRegImm64(amd64.R10, 16)
	e.MovDerefReg(amd64.R12, amd64ByteBufferLength, amd64.R10)
	e.MovRegReg(amd64.RAX, amd64.R12)
	returnJump := len(e.Code)
	e.JmpRel32(0)

	failure := len(e.Code)
	for _, at := range invalid {
		patchJcc(at, failure)
	}
	patchJmp(badHex, failure)
	patchJcc(badHexLow, failure)
	patchJcc(belowA, failure)
	patchJcc(belowa, failure)
	e.MovRegImm64(amd64.R10, 0)
	e.Cvtsi2sd(amd64.XMM0, amd64.R10)
	callEmpty := len(e.Code)
	e.CallRel32(int32(byteBufferNewOffset - (callEmpty + 5)))

	returnLabel := len(e.Code)
	patchJmp(returnJump, returnLabel)
	e.AddRegImm32(amd64.RSP, 160)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}

func emitAMD64NetHTTPRequestIPv6(e *amd64.Emitter, byteBufferNewOffset, byteBufferCopyOffset, taskYieldOffset int) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }

	e.Push(amd64.RBP)
	e.MovRegReg(amd64.RBP, amd64.RSP)
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	e.SubRegImm32(amd64.RSP, 96)
	e.MovRegReg(amd64.RBX, amd64.RDI)       // resolved IPv6 address ByteBuffer
	e.MovDerefReg(amd64.RSP, 32, amd64.RSI) // port string
	e.MovRegReg(amd64.R12, amd64.RDX)       // request buffer
	e.MovDerefReg(amd64.RSP, 40, amd64.RCX) // AbortSignal, survives cooperative yields

	// sockaddr_in6: AF_INET6, port, flowinfo=0, 16-byte address, scope_id=0.
	for off, value := range make([]byte, 28) {
		if off == 0 {
			value = 10
		}
		e.MovRegImm64(amd64.R11, int64(value))
		e.MovDerefReg8(amd64.RSP, int32(off), amd64.R11)
	}
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64ByteBufferData)
	for i := 0; i < 16; i++ {
		e.MovzxRegDeref8(amd64.R11, amd64.R10, int32(i))
		e.MovDerefReg8(amd64.RSP, int32(8+i), amd64.R11)
	}

	// Parse decimal port, defaulting empty to 80.
	e.MovRegDeref(amd64.RBX, amd64.RSP, 32)
	e.MovRegDeref(amd64.R10, amd64.RBX, 0)
	e.MovRegImm64(amd64.R13, 0)
	e.MovRegImm64(amd64.R14, 0)
	e.TestRegReg(amd64.R10, amd64.R10)
	portLoopStartJump := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.MovRegImm64(amd64.R13, 80)
	portDoneJump := len(e.Code)
	e.JmpRel32(0)
	portLoop := len(e.Code)
	patchJcc(portLoopStartJump, portLoop)
	e.CmpRegReg(amd64.R14, amd64.R10)
	portParsed := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.R11, amd64.RBX)
	e.AddRegImm32(amd64.R11, 8)
	e.AddRegReg(amd64.R11, amd64.R14)
	e.MovzxRegDeref8(amd64.R11, amd64.R11, 0)
	e.SubRegImm32(amd64.R11, 48)
	e.MovRegImm64(amd64.RAX, 10)
	e.ImulRegReg(amd64.R13, amd64.RAX)
	e.AddRegReg(amd64.R13, amd64.R11)
	e.AddRegImm32(amd64.R14, 1)
	back := len(e.Code)
	e.JmpRel32(0)
	patchJmp(back, portLoop)
	portReady := len(e.Code)
	patchJcc(portParsed, portReady)
	patchJmp(portDoneJump, portReady)

	// socket(AF_INET6, SOCK_STREAM, 0)
	e.MovRegImm64(amd64.RAX, 41)
	e.MovRegImm64(amd64.RDI, 10)
	e.MovRegImm64(amd64.RSI, 1)
	e.MovRegImm64(amd64.RDX, 0)
	e.Syscall()
	e.MovRegReg(amd64.R14, amd64.RAX) // fd
	e.TestRegReg(amd64.R14, amd64.R14)
	socketFailed := len(e.Code)
	e.JccRel32(amd64.CondL, 0)

	e.MovRegReg(amd64.R10, amd64.R13)
	e.ShrRegImm8(amd64.R10, 8)
	e.MovRegImm64(amd64.R11, 255)
	e.AndRegReg(amd64.R10, amd64.R11)
	e.MovDerefReg8(amd64.RSP, 2, amd64.R10)
	e.MovRegReg(amd64.R10, amd64.R13)
	e.AndRegReg(amd64.R10, amd64.R11)
	e.MovDerefReg8(amd64.RSP, 3, amd64.R10)

	// Make the socket nonblocking before connect/write/read. Slow peers must not
	// pin the cooperative scheduler and starve AbortSignal timers.
	e.MovRegImm64(amd64.RAX, 72) // fcntl
	e.MovRegReg(amd64.RDI, amd64.R14)
	e.MovRegImm64(amd64.RSI, 4)    // F_SETFL
	e.MovRegImm64(amd64.RDX, 2048) // O_NONBLOCK
	e.Syscall()
	e.TestRegReg(amd64.RAX, amd64.RAX)
	fcntlFailed := len(e.Code)
	e.JccRel32(amd64.CondL, 0)

	connectLoop := len(e.Code)
	e.MovRegDeref(amd64.R10, amd64.RSP, 40)
	e.MovRegDeref(amd64.R11, amd64.R10, amd64AbortSignalAborted)
	e.TestRegReg(amd64.R11, amd64.R11)
	abortedConnect := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)

	// connect(fd, &sockaddr_in6, 28). EINPROGRESS/EALREADY are cooperative waits;
	// EISCONN means a retried nonblocking connect has completed.
	e.MovRegImm64(amd64.RAX, 42)
	e.MovRegReg(amd64.RDI, amd64.R14)
	e.MovRegReg(amd64.RSI, amd64.RSP)
	e.MovRegImm64(amd64.RDX, 28)
	e.Syscall()
	e.TestRegReg(amd64.RAX, amd64.RAX)
	connectOK := len(e.Code)
	e.JccRel32(amd64.CondGE, 0)
	e.CmpRegImm32(amd64.RAX, -106) // EISCONN
	connectIsConn := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	var connectRetry []int
	for _, errno := range []int32{-115, -114, -4} { // EINPROGRESS, EALREADY, EINTR
		e.CmpRegImm32(amd64.RAX, errno)
		at := len(e.Code)
		e.JccRel32(amd64.CondE, 0)
		connectRetry = append(connectRetry, at)
	}
	connectFailed := len(e.Code)
	e.JmpRel32(0)
	connectYield := len(e.Code)
	for _, at := range connectRetry {
		patchJcc(at, connectYield)
	}
	callConnectYield := len(e.Code)
	e.CallRel32(int32(taskYieldOffset - (callConnectYield + 5)))
	connectBack := len(e.Code)
	e.JmpRel32(int32(connectLoop - (connectBack + 5)))
	connected := len(e.Code)
	patchJcc(connectOK, connected)
	patchJcc(connectIsConn, connected)

	// Write the complete request. Partial writes and EAGAIN yield rather than
	// silently truncating the request body.
	e.MovRegImm64(amd64.R13, 0) // bytes written
	writeLoop := len(e.Code)
	e.MovRegDeref(amd64.R10, amd64.RSP, 40)
	e.MovRegDeref(amd64.R11, amd64.R10, amd64AbortSignalAborted)
	e.TestRegReg(amd64.R11, amd64.R11)
	abortedWrite := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.MovRegDeref(amd64.R10, amd64.R12, amd64ByteBufferLength)
	e.CmpRegReg(amd64.R13, amd64.R10)
	writeComplete := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegImm64(amd64.RAX, 1)
	e.MovRegReg(amd64.RDI, amd64.R14)
	e.MovRegDeref(amd64.RSI, amd64.R12, amd64ByteBufferData)
	e.AddRegReg(amd64.RSI, amd64.R13)
	e.MovRegReg(amd64.RDX, amd64.R10)
	e.SubRegReg(amd64.RDX, amd64.R13)
	e.Syscall()
	e.TestRegReg(amd64.RAX, amd64.RAX)
	writeProgress := len(e.Code)
	e.JccRel32(amd64.CondG, 0)
	var writeRetry []int
	e.CmpRegImm32(amd64.RAX, 0)
	writeZero := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	writeRetry = append(writeRetry, writeZero)
	for _, errno := range []int32{-11, -4} { // EAGAIN/EWOULDBLOCK, EINTR
		e.CmpRegImm32(amd64.RAX, errno)
		at := len(e.Code)
		e.JccRel32(amd64.CondE, 0)
		writeRetry = append(writeRetry, at)
	}
	writeFailed := len(e.Code)
	e.JmpRel32(0)
	writeYield := len(e.Code)
	for _, at := range writeRetry {
		patchJcc(at, writeYield)
	}
	callWriteYield := len(e.Code)
	e.CallRel32(int32(taskYieldOffset - (callWriteYield + 5)))
	writeRetryBack := len(e.Code)
	e.JmpRel32(int32(writeLoop - (writeRetryBack + 5)))
	writeProgressLabel := len(e.Code)
	patchJcc(writeProgress, writeProgressLabel)
	e.AddRegReg(amd64.R13, amd64.RAX)
	writeProgressBack := len(e.Code)
	e.JmpRel32(int32(writeLoop - (writeProgressBack + 5)))
	writeDone := len(e.Code)
	patchJcc(writeComplete, writeDone)

	// Start with 64KiB and grow geometrically while reading until EOF.
	e.MovRegImm64(amd64.R10, 64*1024)
	e.Cvtsi2sd(amd64.XMM0, amd64.R10)
	callNew := len(e.Code)
	e.CallRel32(int32(byteBufferNewOffset - (callNew + 5)))
	e.MovRegReg(amd64.RBX, amd64.RAX)
	e.MovRegImm64(amd64.R10, 0)
	e.MovDerefReg(amd64.RBX, amd64ByteBufferLength, amd64.R10)
	// Root the response buffer while scheduler yields can run arbitrary tasks/GC.
	e.MovRegDeref(amd64.R10, amd64.R15, amd64RTRootHead)
	e.MovDerefReg(amd64.RSP, 64, amd64.R10)
	e.MovRegImm64(amd64.R10, 1)
	e.MovDerefReg(amd64.RSP, 72, amd64.R10)
	e.MovDerefReg(amd64.RSP, 80, amd64.RBX)
	e.MovRegReg(amd64.R10, amd64.RSP)
	e.AddRegImm32(amd64.R10, 64)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.R10)

	e.MovRegImm64(amd64.R13, 0) // response bytes used
	readLoop := len(e.Code)
	// AbortSignal.aborted is a native boolean field. The caller still owns the
	// signal root while this runtime helper cooperatively suspends and resumes.
	e.MovRegDeref(amd64.R10, amd64.RSP, 40)
	e.MovRegDeref(amd64.R11, amd64.R10, amd64AbortSignalAborted)
	e.TestRegReg(amd64.R11, amd64.R11)
	abortedRead := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)

	// Grow when the buffer is full. R12 is free after request write completion,
	// so it temporarily keeps the old rooted response during replacement.
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64ByteBufferCapacity)
	e.CmpRegReg(amd64.R13, amd64.R10)
	haveCapacity := len(e.Code)
	e.JccRel32(amd64.CondB, 0)
	e.MovRegReg(amd64.R12, amd64.RBX)
	e.AddRegReg(amd64.R10, amd64.R10)
	e.Cvtsi2sd(amd64.XMM0, amd64.R10)
	callGrow := len(e.Code)
	e.CallRel32(int32(byteBufferNewOffset - (callGrow + 5)))
	e.MovRegReg(amd64.RBX, amd64.RAX)
	// The precise root must follow the replacement before any subsequent yield.
	e.MovDerefReg(amd64.RSP, 80, amd64.RBX)
	e.MovRegReg(amd64.RDI, amd64.RBX)
	e.MovRegReg(amd64.RSI, amd64.R12)
	e.MovRegImm64(amd64.R10, 0)
	e.Cvtsi2sd(amd64.XMM0, amd64.R10)
	e.Cvtsi2sd(amd64.XMM1, amd64.R10)
	e.Cvtsi2sd(amd64.XMM2, amd64.R13)
	callCopy := len(e.Code)
	e.CallRel32(int32(byteBufferCopyOffset - (callCopy + 5)))
	e.MovDerefReg(amd64.RBX, amd64ByteBufferLength, amd64.R13)
	haveCapacityLabel := len(e.Code)
	patchJcc(haveCapacity, haveCapacityLabel)

	// read(fd, response.data+used, capacity-used)
	e.MovRegDeref(amd64.R10, amd64.RBX, amd64ByteBufferCapacity)
	e.MovRegReg(amd64.RDX, amd64.R10)
	e.SubRegReg(amd64.RDX, amd64.R13)
	e.MovRegImm64(amd64.RAX, 0)
	e.MovRegReg(amd64.RDI, amd64.R14)
	e.MovRegDeref(amd64.RSI, amd64.RBX, amd64ByteBufferData)
	e.AddRegReg(amd64.RSI, amd64.R13)
	e.Syscall()
	e.TestRegReg(amd64.RAX, amd64.RAX)
	readProgress := len(e.Code)
	e.JccRel32(amd64.CondG, 0)
	readEOF := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	// EAGAIN/EWOULDBLOCK or EINTR: yield so timers/microtasks can run, then retry.
	e.CmpRegImm32(amd64.RAX, -11)
	wouldBlock := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.CmpRegImm32(amd64.RAX, -4)
	interrupted := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	// Other read failures return the bytes already received.
	readFailure := len(e.Code)
	e.JmpRel32(0)
	yieldLabel := len(e.Code)
	patchJcc(wouldBlock, yieldLabel)
	patchJcc(interrupted, yieldLabel)
	callYield := len(e.Code)
	e.CallRel32(int32(taskYieldOffset - (callYield + 5)))
	retryRead := len(e.Code)
	e.JmpRel32(int32(readLoop - (retryRead + 5)))
	readProgressLabel := len(e.Code)
	patchJcc(readProgress, readProgressLabel)
	e.AddRegReg(amd64.R13, amd64.RAX)
	e.MovDerefReg(amd64.RBX, amd64ByteBufferLength, amd64.R13)
	readMore := len(e.Code)
	e.JmpRel32(int32(readLoop - (readMore + 5)))
	readDone := len(e.Code)
	patchJcc(readEOF, readDone)
	patchJmp(readFailure, readDone)
	e.MovDerefReg(amd64.RBX, amd64ByteBufferLength, amd64.R13)
	responseCloseJump := len(e.Code)
	e.JmpRel32(0)
	abortedLabel := len(e.Code)
	patchJcc(abortedRead, abortedLabel)
	e.MovRegImm64(amd64.R10, 0)
	e.MovDerefReg(amd64.RBX, amd64ByteBufferLength, amd64.R10)
	responseClose := len(e.Code)
	patchJmp(responseCloseJump, responseClose)
	// Pop the runtime-local precise root before returning to the caller frame.
	e.MovRegDeref(amd64.R10, amd64.RSP, 64)
	e.MovDerefReg(amd64.R15, amd64RTRootHead, amd64.R10)
	e.MovRegImm64(amd64.RAX, 3)
	e.MovRegReg(amd64.RDI, amd64.R14)
	e.Syscall()
	e.MovRegReg(amd64.RAX, amd64.RBX)
	returnJump := len(e.Code)
	e.JmpRel32(0)

	// Failures/aborts before response allocation close the fd and return an empty buffer.
	failureWithFD := len(e.Code)
	patchJcc(fcntlFailed, failureWithFD)
	patchJcc(abortedConnect, failureWithFD)
	patchJmp(connectFailed, failureWithFD)
	patchJcc(abortedWrite, failureWithFD)
	patchJmp(writeFailed, failureWithFD)
	e.MovRegImm64(amd64.RAX, 3)
	e.MovRegReg(amd64.RDI, amd64.R14)
	e.Syscall()
	failureNoFD := len(e.Code)
	patchJcc(socketFailed, failureNoFD)
	e.MovRegImm64(amd64.R10, 0)
	e.Cvtsi2sd(amd64.XMM0, amd64.R10)
	callEmpty := len(e.Code)
	e.CallRel32(int32(byteBufferNewOffset - (callEmpty + 5)))

	returnLabel := len(e.Code)
	patchJmp(returnJump, returnLabel)
	e.AddRegImm32(amd64.RSP, 96)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Pop(amd64.RBP)
	e.Ret()
}
