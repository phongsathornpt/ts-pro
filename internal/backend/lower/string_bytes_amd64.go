func emitAMD64StringFindLastByte(e *amd64.Emitter) {
	patchJcc := func(at, target int) {
		binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6))))
	}
	e.Cvttsd2si(amd64.R8, amd64.XMM0) // byte
	e.MovRegDeref(amd64.R9, amd64.RDI, 0)
	e.TestRegReg(amd64.R9, amd64.R9)
	empty := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.SubRegImm32(amd64.R9, 1)
	loop := len(e.Code)
	e.MovRegReg(amd64.R10, amd64.RDI)
	e.AddRegImm32(amd64.R10, 8)
	e.AddRegReg(amd64.R10, amd64.R9)
	e.MovzxRegDeref8(amd64.RAX, amd64.R10, 0)
	e.CmpRegReg(amd64.RAX, amd64.R8)
	found := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.TestRegReg(amd64.R9, amd64.R9)
	miss := len(e.Code)
	e.JccRel32(amd64.CondE, 0)
	e.SubRegImm32(amd64.R9, 1)
	back := len(e.Code)
	e.JmpRel32(0)
	binary.LittleEndian.PutUint32(e.Code[back+1:], uint32(int32(loop-(back+5))))
	foundLabel := len(e.Code)
	patchJcc(found, foundLabel)
	e.MovRegReg(amd64.RAX, amd64.R9)
	e.Cvtsi2sd(amd64.XMM0, amd64.RAX)
	e.Ret()
	missLabel := len(e.Code)
	patchJcc(empty, missLabel)
	patchJcc(miss, missLabel)
	e.MovRegImm64(amd64.RAX, -1)
	e.Cvtsi2sd(amd64.XMM0, amd64.RAX)
	e.Ret()
}

// emitAMD64StringFind searches needle in haystack starting at byte offset.
// RDI=haystack, RSI=needle, XMM0=start, XMM0=result index or -1.
func emitAMD64StringFind(e *amd64.Emitter) {
	patchJcc := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+2:], uint32(int32(target-(at+6)))) }
	patchJmp := func(at, target int) { binary.LittleEndian.PutUint32(e.Code[at+1:], uint32(int32(target-(at+5)))) }
	e.Push(amd64.RBX)
	e.Push(amd64.R12)
	e.Push(amd64.R13)
	e.Push(amd64.R14)
	e.MovRegReg(amd64.RBX, amd64.RDI)
	e.MovRegReg(amd64.R12, amd64.RSI)
	e.Cvttsd2si(amd64.R13, amd64.XMM0)
	e.MovRegDeref(amd64.R10, amd64.RBX, 0)
	e.MovRegDeref(amd64.R11, amd64.R12, 0)
	e.TestRegReg(amd64.R13, amd64.R13)
	startOK := len(e.Code)
	e.JccRel32(amd64.CondGE, 0)
	e.MovRegImm64(amd64.R13, 0)
	patchJcc(startOK, len(e.Code))
	// Empty needle matches at min(start, haystack length).
	e.TestRegReg(amd64.R11, amd64.R11)
	nonEmpty := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.CmpRegReg(amd64.R13, amd64.R10)
	emptyInRange := len(e.Code)
	e.JccRel32(amd64.CondBE, 0)
	e.MovRegReg(amd64.R13, amd64.R10)
	patchJcc(emptyInRange, len(e.Code))
	e.Cvtsi2sd(amd64.XMM0, amd64.R13)
	doneEmpty := len(e.Code)
	e.JmpRel32(0)
	patchJcc(nonEmpty, len(e.Code))

	// Last viable start = haystackLen - needleLen.
	e.MovRegReg(amd64.R14, amd64.R10)
	e.SubRegReg(amd64.R14, amd64.R11)
	e.CmpRegReg(amd64.R10, amd64.R11)
	tooShort := len(e.Code)
	e.JccRel32(amd64.CondB, 0)

	outer := len(e.Code)
	e.CmpRegReg(amd64.R13, amd64.R14)
	notFound := len(e.Code)
	e.JccRel32(amd64.CondA, 0)
	e.MovRegImm64(amd64.R8, 0)
	inner := len(e.Code)
	e.CmpRegReg(amd64.R8, amd64.R11)
	found := len(e.Code)
	e.JccRel32(amd64.CondAE, 0)
	e.MovRegReg(amd64.R9, amd64.RBX)
	e.AddRegImm32(amd64.R9, 8)
	e.AddRegReg(amd64.R9, amd64.R13)
	e.AddRegReg(amd64.R9, amd64.R8)
	e.MovzxRegDeref8(amd64.RAX, amd64.R9, 0)
	e.MovRegReg(amd64.RDX, amd64.R12)
	e.AddRegImm32(amd64.RDX, 8)
	e.AddRegReg(amd64.RDX, amd64.R8)
	e.MovzxRegDeref8(amd64.R9, amd64.RDX, 0)
	e.CmpRegReg(amd64.RAX, amd64.R9)
	mismatch := len(e.Code)
	e.JccRel32(amd64.CondNE, 0)
	e.AddRegImm32(amd64.R8, 1)
	innerBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(innerBack, inner)

	mismatchLabel := len(e.Code)
	patchJcc(mismatch, mismatchLabel)
	e.AddRegImm32(amd64.R13, 1)
	outerBack := len(e.Code)
	e.JmpRel32(0)
	patchJmp(outerBack, outer)

	foundLabel := len(e.Code)
	patchJcc(found, foundLabel)
	e.Cvtsi2sd(amd64.XMM0, amd64.R13)
	foundDone := len(e.Code)
	e.JmpRel32(0)

	notFoundLabel := len(e.Code)
	patchJcc(notFound, notFoundLabel)
	patchJcc(tooShort, notFoundLabel)
	e.MovRegImm64(amd64.RAX, -1)
	e.Cvtsi2sd(amd64.XMM0, amd64.RAX)

	done := len(e.Code)
	patchJmp(doneEmpty, done)
	patchJmp(foundDone, done)
	e.Pop(amd64.R14)
	e.Pop(amd64.R13)
	e.Pop(amd64.R12)
	e.Pop(amd64.RBX)
	e.Ret()
}
